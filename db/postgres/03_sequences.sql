-- SQL Server has 0 user-created SEQUENCE objects. It has 17 legacy int/bigint IDENTITY
-- columns (the other 5 "identity-like" hits from sys.identity_columns are SQL Server system
-- objects -- sys.queue_messages_*, sys.sqlagent_job_history/jobsteps_logs -- and are excluded;
-- they are Service Broker / SQL Agent internals with no application meaning and no Postgres
-- equivalent needed).
--
-- All 17 real identity columns are on legacy pre-multitenant tables that predate the
-- TenantId/uniqueidentifier convention used everywhere else in this schema:
--   dbo.Address.AddressId, dbo.BankDetail.BankId, dbo.Driver.DriverId, dbo.Guardian.GuardianId,
--   dbo.MedicalInfo.MedicalId, dbo.Organization.OrganizationId, dbo.Organizations.OrganizationId,
--   dbo.Parent.ParentId, dbo.PreviousSchool.Id, dbo.Route.RouteId, dbo.Sibling.SiblingId,
--   dbo.Student.StudentId, dbo.StudentDocument.DocumentId, dbo.StudentLanguage.Id,
--   dbo.Transport.TransportId, dbo.Vehicle.VehicleId  (all seed 1, increment 1)
--   dbo.UserLogin.Id  (seed 1001, increment 1)
--
-- PostgreSQL does not need separate CREATE SEQUENCE statements for these: each is declared
-- directly on its column in 04_tables.sql as
--   GENERATED BY DEFAULT AS IDENTITY (START WITH <seed> INCREMENT BY <increment>)
-- which creates and owns an internal sequence automatically, matching SQL Server IDENTITY
-- semantics (BY DEFAULT, not ALWAYS, so explicit-value inserts remain possible exactly as
-- SET IDENTITY_INSERT ON permits in SQL Server -- confirm no application code currently uses
-- SET IDENTITY_INSERT before relying on this; none was found in the migrations scanned).
--
-- This file exists to document that no separate sequence DDL is required; there is nothing to
-- execute here.
