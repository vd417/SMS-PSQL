-- 0020: dbo.ChatBannedWords — banned words/phrases for the in-app chat profanity filter.
--
-- WHY: the mobile chat shows a standing notice ("Inappropriate language or images are not allowed
-- in school chat. Violations may result in a notice from your school.") but nothing enforced it.
-- The backend now checks every outbound chat message (ThreadService.SendMessageAsync) against this
-- list and rejects a match with error code "inappropriate_content" (HTTP 422) so every client
-- (mobile apps AND sms-admin) shows the notice/popup instead of sending. Matching is token-exact
-- for single words (so "class" is NOT caught by "ass") and collapsed-substring for phrases; see
-- ChatContentFilter. Simple symbol de-leet (@->a $->s !->i, * # stripped) catches a$$, f**k, etc.
--
-- TenantId NULL = global (applies to every school). A school can later get its own rows (same
-- NULL-or-tenant RLS read used below). Seeded with the school-provided list (English + Hindi
-- Devanagari + Hinglish + regional + leet variants). Additive: a new table, index, RLS, grant, seed.
-- Rollback: DROP TABLE "dbo"."ChatBannedWords";

CREATE TABLE IF NOT EXISTS "dbo"."ChatBannedWords" (
    "Id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    "TenantId" uuid NULL,                       -- NULL = global (all schools)
    "Kind" varchar(10) NOT NULL DEFAULT 'single' CHECK ("Kind" IN ('single','phrase')),
    "Word" varchar(100) NOT NULL,
    "CreatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS "IX_ChatBannedWords_Tenant" ON "dbo"."ChatBannedWords" ("TenantId");

ALTER TABLE "dbo"."ChatBannedWords" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "dbo"."ChatBannedWords" FORCE ROW LEVEL SECURITY;
-- SELECT also exposes global (NULL-tenant) rows to every tenant's app connection.
CREATE POLICY "ChatBannedWordsTenantPolicy_select" ON "dbo"."ChatBannedWords" FOR SELECT USING (rls.is_platform() OR "TenantId" IS NULL OR "TenantId" = rls.current_tenant_id());
CREATE POLICY "ChatBannedWordsTenantPolicy_update" ON "dbo"."ChatBannedWords" FOR UPDATE USING (rls.is_platform() OR "TenantId" = rls.current_tenant_id()) WITH CHECK (rls.is_platform() OR "TenantId" = rls.current_tenant_id());
CREATE POLICY "ChatBannedWordsTenantPolicy_delete" ON "dbo"."ChatBannedWords" FOR DELETE USING (rls.is_platform() OR "TenantId" = rls.current_tenant_id());
CREATE POLICY "ChatBannedWordsTenantPolicy_insert" ON "dbo"."ChatBannedWords" FOR INSERT WITH CHECK (rls.is_platform() OR "TenantId" = rls.current_tenant_id());

-- 99_app_role_grants.sql ran before this table existed.
GRANT SELECT, INSERT, UPDATE, DELETE ON "dbo"."ChatBannedWords" TO sms_app;

